# Program demonstrujący użycie zmiennych w Pythonie
# Przykład związany z biologią molekularną

gen = 'BRCA1'                 # Zmienna typu string
liczba_mutacji = 3            # Zmienna typu integer
masa_bialka = 58.44           # Zmienna typu float

print(gen, liczba_mutacji, masa_bialka)   # Wyświetlenie wielu zmiennych o różnych typach

print(type(gen))              # Sprawdzenie typu zmiennej gen
print(type(liczba_mutacji))   # Sprawdzenie typu zmiennej liczba_mutacji
print(type(masa_bialka))      # Sprawdzenie typu zmiennej masa_bialkasource venw/bin/activate

